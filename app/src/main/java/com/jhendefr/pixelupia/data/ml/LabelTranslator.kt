    fun translate(label: String): String {
        val trimmed = label.trim()
        if (trimmed.isBlank()) return "Objeto"

        val lower = trimmed.lowercase(Locale.ROOT)

        // 1. Busqueda exacta en diccionario
        dictionary[lower]?.let { return capitalizeWords(it) }

        // 2. Normalizacion de sufijos plurales en ingles
        if (lower.endsWith("ies") && lower.length > 3) {
            val singularY = lower.removeSuffix("ies") + "y"
            dictionary[singularY]?.let { return capitalizeWords(it) }
            val singularS = lower.removeSuffix("s")
            dictionary[singularS]?.let { return capitalizeWords(it) }
        }
        if (lower.endsWith("es") && lower.length > 3) {
            val singularEs = lower.removeSuffix("es")
            dictionary[singularEs]?.let { return capitalizeWords(it) }
        }
        if (lower.endsWith("s") && lower.length > 2 && !lower.endsWith("ss")) {
            val singularS = lower.removeSuffix("s")
            dictionary[singularS]?.let { return capitalizeWords(it) }
        }

        // 3. Manejo de terminos compuestos (ej: "night club", "cell phone", etc.)
        val tokens = lower.split(Regex("[\\s_\\-]+"))
        if (tokens.size > 1) {
            val translatedTokens = tokens.map { token ->
                dictionary[token]
                    ?: (if (token.endsWith("s") && token.length > 2) dictionary[token.removeSuffix("s")] else null)
                    ?: token
            }
            val joined = translatedTokens.joinToString(" ")
            if (joined != lower) {
                return capitalizeWords(joined)
            }
        }

        // 4. Si no esta en el diccionario, devolver la cadena capitalizada adecuadamente
        return capitalizeWords(trimmed)
    }

    private fun capitalizeWords(str: String): String {
        return str.split(" ").joinToString(" ") { word ->
            word.replaceFirstChar { if (it.isLowerCase()) it.titlecase(Locale.ROOT) else it.toString() }
        }
    }
